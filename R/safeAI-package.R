#' safeAI: Univariate Rank Graduation Metrics for SAFE AI
#'
#' `safeAI` provides a model-agnostic toolkit for univariate rank graduation
#' accuracy (`rga()`), robustness (`rgr()`), and explainability (`rge()`). It
#' also provides Lorenz, dual Lorenz, concordance, and combined curve helpers.
#'
#' The package calculates metrics from vectors supplied by the user. Model
#' fitting, reduced-model construction, and robustness-scenario design remain
#' separate from the metric functions.
#'
#' @references
#' Giudici, P. and Raffinetti, E. (2025). RGA: A unified measure of predictive
#' accuracy. *Advances in Data Analysis and Classification*, 19, 67-93.
#'
#' @keywords internal
